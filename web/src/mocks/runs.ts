import type { Run, CompanyRun, RunStep, RunLog } from '@/types'

function steps(statuses: Partial<Record<string, { status: RunStep['status']; message: string; durationMs?: number }>>): RunStep[] {
  const defs: { key: string; label: string; defaultMsg: string }[] = [
    { key: 'robots', label: 'robots 检查', defaultMsg: 'robots.txt 允许抓取招聘路径' },
    { key: 'homepage', label: '首页抓取', defaultMsg: '首页抓取成功，HTTP 200' },
    { key: 'entry', label: '招聘入口识别', defaultMsg: '识别到招聘入口页面' },
    { key: 'list', label: '招聘列表抓取', defaultMsg: '抓取招聘列表页完成' },
    { key: 'detail', label: '职位详情抓取', defaultMsg: '职位详情页抓取完成' },
    { key: 'llm', label: 'LLM 提取', defaultMsg: '岗位结构化提取完成' },
    { key: 'dedup', label: '数据去重', defaultMsg: '与历史岗位比对完成' },
    { key: 'report', label: '日报生成', defaultMsg: '日报内容已汇总' },
    { key: 'email', label: '邮件通知', defaultMsg: '邮件通知未启用，跳过' },
  ]
  return defs.map((d) => {
    const o = statuses[d.key]
    return {
      key: d.key,
      label: d.label,
      status: o?.status ?? 'success',
      message: o?.message ?? d.defaultMsg,
      durationMs: o?.durationMs ?? 800 + Math.floor(Math.random() * 2400),
    }
  })
}

