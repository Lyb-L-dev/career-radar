function difficultyFactors(overrides?: Partial<DifficultyFactor>[]): DifficultyFactor[] {
  const base: DifficultyFactor[] = [
    { label: '技术要求', level: '中', note: '要求掌握岗位核心技术栈' },
    { label: '工作经验', level: '低', note: '接受应届生或实习生' },
    { label: '学历要求', level: '低', note: '本科及以上' },
    { label: '工具熟悉度', level: '中', note: '需要了解团队常用工具链' },
    { label: '岗位竞争程度', level: '中', note: '同类岗位投递量中等' },
  ]
  if (!overrides) return base
  return base.map((f, i) => ({ ...f, ...(overrides[i] ?? {}) }))
}

function source(companyName: string, page: string, method = 'requests 静态抓取'): SourceCredibility {
  return {
    site: companyName,
    page,
    method,
    urlVerified: true,
    lastVerifiedAt: '2026-07-18 09:47',
  }
}

function history(...items: JobChange[]): JobChange[] {
  return items
}

